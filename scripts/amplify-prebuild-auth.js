/**
 * Run before `next build` on Amplify. Edge middleware cannot read amplify-auth.json; we embed
 * NEXTAUTH_SECRET in the middleware bundle. Read it from `.next/amplify-auth.json` when present
 * so it always matches what Node uses (serverEnv prefers the file over runtime env).
 */
const fs = require("fs");
const path = require("path");

const jsonPath = path.join(process.cwd(), ".next", "amplify-auth.json");
let secret = process.env.NEXTAUTH_SECRET ?? "";

if (fs.existsSync(jsonPath)) {
  try {
    const parsed = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
    if (typeof parsed.NEXTAUTH_SECRET === "string" && parsed.NEXTAUTH_SECRET !== "") {
      secret = parsed.NEXTAUTH_SECRET;
    }
  } catch {
    /* keep env fallback */
  }
}

const target = path.join(process.cwd(), "lib", "generated-middleware-secret.ts");

const body = `/**
 * Auto-generated by scripts/amplify-prebuild-auth.js — do not edit.
 * Matches .next/amplify-auth.json NEXTAUTH_SECRET when that file exists (Amplify build).
 */
export const BUILD_TIME_NEXTAUTH_SECRET: string = ${JSON.stringify(secret)};
`;

fs.writeFileSync(target, body, "utf8");
console.log(
  "[amplify-prebuild-auth] wrote",
  target,
  secret ? "(secret length " + secret.length + ")" : "(empty — set NEXTAUTH_SECRET in Amplify for this branch)"
);
